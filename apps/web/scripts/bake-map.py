# Bakes simplified country outlines (Natural Earth 1:50m via world-atlas, public domain) for each
# company's region into a small TypeScript module of SVG paths. Usage: bake_map.py <topojson> <out.ts>
import json, math, sys
topo = json.load(open(sys.argv[1]))
sx, sy = topo['transform']['scale']; tx, ty = topo['transform']['translate']
arcs = []
for arc in topo['arcs']:
    x = y = 0; pts = []
    for dx, dy in arc:
        x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)
def ring(idx):
    out = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(a if not out else a[1:])
    return out
NUM = {'404':'KE','800':'UG','834':'TZ','646':'RW','108':'BI','728':'SS','231':'ET','706':'SO','180':'CD','894':'ZM','454':'MW','508':'MZ','729':'SD',
       '784':'AE','682':'SA','048':'BH','512':'OM','634':'QA','414':'KW','887':'YE','368':'IQ','364':'IR','400':'JO','818':'EG','760':'SY','376':'IL','232':'ER','262':'DJ',
       '826':'GB','250':'FR','276':'DE','528':'NL','056':'BE','442':'LU','372':'IE','756':'CH','040':'AT','208':'DK','724':'ES','380':'IT','616':'PL','203':'CZ','620':'PT','752':'SE','578':'NO'}
REGIONS = {
  'EA':   {'lon': (28.5, 41.5), 'lat': (-9.0, 2.5), 'only': {'KE','UG','TZ','RW','BI','SS','ET','SO','CD','ZM','MW','MZ'}},
  'GULF': {'lon': (37.0, 60.0), 'lat': (18.0, 29.5), 'only': {'AE','SA','BH','OM','QA','KW','YE','IQ','IR','JO','EG','ER','DJ','IL','SY'}},
  'EU':   {'lon': (-7.0, 15.5), 'lat': (43.0, 56.5), 'only': {'GB','FR','DE','NL','BE','LU','IE','CH','AT','DK','ES','IT','PL','CZ'}},
}
W = 1000.0
def dp(pts, eps):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; dmax = 0; idx = 0
    ax, ay = a; bx, by = b; L = math.hypot(bx-ax, by-ay) or 1e-9
    for i in range(1, len(pts)-1):
        px, py = pts[i]; d = abs((bx-ax)*(ay-py) - (ax-px)*(by-ay)) / L
        if d > dmax: dmax, idx = d, i
    if dmax > eps: return dp(pts[:idx+1], eps)[:-1] + dp(pts[idx:], eps)
    return [a, b]
out = ['// Generated by bake_map.py from Natural Earth 1:50m country outlines (public domain, via',
       '// world-atlas 2.0.2). Equirectangular, scaled by cos(mid-latitude); x and y in a 1000-wide box.',
       '', 'export interface RegionMap { viewBox: string; lon: [number, number]; lat: [number, number]; k: number; countries: { code: string; d: string }[] }', '',
       'export const REGION_MAPS: Record<string, RegionMap> = {']
for name, r in REGIONS.items():
    (lo0, lo1), (la0, la1) = r['lon'], r['lat']
    k = math.cos(math.radians((la0 + la1) / 2))
    scale = W / ((lo1 - lo0) * k)
    H = (la1 - la0) * scale
    proj = lambda lon, lat: ((lon - lo0) * k * scale, (la1 - lat) * scale)
    shapes = []
    for g in topo['objects']['countries']['geometries']:
        code = NUM.get(str(g.get('id')).zfill(3))
        if not code or code not in r['only']: continue
        polys = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']] if g['type'] == 'Polygon' else []
        parts = []
        for poly in polys:
            for ri, rg in enumerate(poly):
                pts = ring(rg)
                lons = [p[0] for p in pts]; lats = [p[1] for p in pts]
                if max(lons) < lo0 or min(lons) > lo1 or max(lats) < la0 or min(lats) > la1: continue
                full = [proj(*p) for p in pts]
                mid = len(full) // 2  # a closed ring starts and ends on one point: simplify each half
                xy = dp(full[:mid + 1], 1.8)[:-1] + dp(full[mid:], 1.8)
                if len(xy) < 4: continue
                parts.append('M' + 'L'.join(f'{round(x)},{round(y)}' for x, y in xy) + 'Z')
        if parts: shapes.append((code, ''.join(parts)))
    out.append(f"  {name}: {{ viewBox: '0 0 {W:.0f} {H:.0f}', lon: [{lo0}, {lo1}], lat: [{la0}, {la1}], k: {k * scale:.4f}, countries: [")
    for code, d in shapes: out.append(f"    {{ code: '{code}', d: '{d}' }},")
    out.append('  ] },')
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('bytes', len('\n'.join(out)))
